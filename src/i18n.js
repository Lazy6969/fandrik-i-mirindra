let L = 0;
export const getLang = () => LANGS[L];
export function setLang(code) {
  L = Math.max(0, LANGS.indexOf(code));
  document.documentElement.lang = LANGS[L];
}
export function t(key, ...args) {
  const v = D[key];
  let s = v ? v[L] : key;
  args.forEach((a, i) => { s = s.replace('{' + i + '}', a); });
  return s;
}
/** Traduit tous les éléments marqués data-i (texte), data-ip (placeholder) et data-ia (aria-label). */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i]').forEach((el) => { el.textContent = t(el.dataset.i); });
  root.querySelectorAll('[data-ip]').forEach((el) => { el.placeholder = t(el.dataset.ip); });
  root.querySelectorAll('[data-ia]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.ia)); });
  document.title = "Fandrik'i Mirindra";
}
